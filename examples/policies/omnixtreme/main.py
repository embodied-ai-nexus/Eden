"""Run the OmniXtreme motion-tracking policy on a Unitree G1 in Genesis.

---
tier: policy
capabilities: [task.mimic, robot.g1]
hardware: cpu
optional_deps: [onnx]
run: uv run python examples/policies/omnixtreme/main.py --motion-file examples/projects/mimic/beyondmimic/sample/G1_gangnam_style_V01_bvh_60hz.npz --vis
---

Tracks an NPZ reference motion (``--motion-file``, generated by BeyondMimic's ``csv_to_npz.py``);
``--debug-vis`` overlays a ghost reference robot.
"""

import os
from argparse import ArgumentParser
from tqdm import tqdm

import genesis as gs

import eden as en
from eden.envs.base import RLEnvBase
from eden.options import (
    ActionManagerOptions,
    CommandManagerOptions,
    EnvOptions,
    ObservationManagerOptions,
)
from eden.options.camera import CameraOptions, CamerasOptions
from eden.extensions.policies.omnixtreme.policy import OmniXtremePolicy
from eden.options import GHOST_DEFAULTS


def main():
    parser = ArgumentParser()
    parser.add_argument(
        "--motion-file",
        type=str,
        required=True,
        help="Path to NPZ motion file (e.g. from BeyondMimic csv_to_npz.py)",
    )
    parser.add_argument("-d", "--debug-vis", action="store_true", help="Draw the debug visualization")
    parser.add_argument("-c", "--cpu", action="store_true", help="Use CPU backend instead of GPU")
    parser.add_argument("-v", "--vis", action="store_true", help="Show viewer")
    parser.add_argument("-r", "--record", action="store_true", help="Record video")

    args = parser.parse_args()

    en.init(backend=gs.cpu if args.cpu else gs.gpu, debug=True)

    if args.debug_vis:
        scene_options = en.scenes.Empty(
            robot=OmniXtremePolicy.robot_options(), ghost_robot=en.robots.G1Dofs29NoHands(**GHOST_DEFAULTS)
        )
    else:
        scene_options = en.scenes.Empty(robot=OmniXtremePolicy.robot_options())

    env = RLEnvBase(
        env_options=EnvOptions(num_envs=1, **OmniXtremePolicy.env_options()),
        scene_options=scene_options,
        command_options=CommandManagerOptions(
            **OmniXtremePolicy.command_options(motion_file=args.motion_file, debug_vis=args.debug_vis)
        ),
        action_options=ActionManagerOptions(**OmniXtremePolicy.action_options()),
        observation_options=ObservationManagerOptions(**OmniXtremePolicy.observation_options()),
        cameras_options=CamerasOptions(
            rec=CameraOptions(
                cam_fov=50.0, follow_entity_name="robot", cam_pos=(1.0, 1.0, 2.5), cam_lookat=(0.0, 0.0, 1.5)
            ),
        )
        if args.record
        else None,
        show_viewer=args.vis,
        eval_mode=True,
    )
    env.build()
    env.config.save_as_json()

    robot = env.entities["robot"]
    policy = OmniXtremePolicy(
        env=env,
        options=OmniXtremePolicy.configure(entity_name="robot"),
    )

    cmd = env.command_manager.get_term("omnixtreme_motion")

    obs, _ = env.reset()

    # Initialize robot base orientation and joint positions from reference motion frame 0,
    frame0_root_quat_wxyz = cmd._body_quat_w[0, 0].unsqueeze(0)
    robot.set_quat(frame0_root_quat_wxyz)
    robot.set_dofs_pos(cmd._joint_pos[0].unsqueeze(0))
    # Recompute observations with the corrected initial pose
    obs = env.observation_manager.compute(update_history=True)

    if args.record:
        rec = env.cameras["rec"]
        motion_name = os.path.splitext(os.path.basename(args.motion_file))[0]
        rec.start_recording(f"{motion_name}.mp4")

    num_frames = cmd._ref_motion_length
    num_steps = num_frames - 1  # motion plays frame-by-frame
    for _ in tqdm(range(num_steps)):
        raw_action = policy.step(obs)
        obs, _, _, _, _ = env.step(raw_action)
        if args.record:
            rec.render_rgb()

    if args.record:
        rec.stop_recording()


if __name__ == "__main__":
    main()
