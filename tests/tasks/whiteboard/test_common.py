"""Tests for the whiteboard workcell: the arm's home pose, the hand's writing orientation and the marker asset."""

import math
import os
import typing
import xml.etree.ElementTree as ET

import pytest
import torch

from eden.tasks.whiteboard import common
from eden.utils.geom import transform_by_quat
from tests.tasks.whiteboard.conftest import build_task


@pytest.fixture(scope="module")
def env():
    return build_task("whiteboard_write_text", num_envs=1)


@pytest.mark.requires_genesis
def test_home_holds_the_nib_30_mm_off_the_drawing_centre_at_the_writing_angle(env):
    arm = env.entities["robot"]
    arm.set_dofs_pos(
        torch.tensor([list(common.HOME.values())]), dofs_idx_local=arm.find_named_dofs(list(common.HOME)).dofs_idx_local
    )
    term = env.action_manager.get_term("arm")
    link = arm.get_link("attachment")
    control = link.get_pos() + transform_by_quat(torch.tensor([term.ee_local_pos]), link.get_quat())
    drawing = env.metric_manager.get_term("drawing")
    torch.testing.assert_close(
        drawing.to_board(control), torch.tensor([[0.0, 0.0, common.HOME_STANDOFF]]), atol=1e-4, rtol=0
    )
    hand = env.entities["robot_gripper"].get_link("hand").get_quat()
    approach = transform_by_quat(torch.tensor([[0.0, 0.0, 1.0]]), hand)[0]
    assert math.degrees(math.acos(float(approach @ drawing.inward))) == pytest.approx(common.HAND_PITCH_DEG, abs=0.1)
    assert float(approach[2]) < 0.0  # nib down


def test_the_hand_points_at_the_board_with_the_nib_tipped_down():
    quat = torch.tensor(common.hand_quat())
    approach = transform_by_quat(torch.tensor([0.0, 0.0, 1.0]), quat)
    pitch = math.radians(common.HAND_PITCH_DEG)
    torch.testing.assert_close(approach, torch.tensor([math.cos(pitch), 0.0, -math.sin(pitch)]), atol=1e-6, rtol=0)


def test_the_marker_asset_has_the_spring_nib_of_the_originals_solid_one():
    root = ET.parse(common.marker_file("green")).getroot()
    slide = root.find(".//joint[@name='nib_slide']")
    # E * A / L of the original's 0.9 MPa, 5 x 2 x 7.5 mm nib.
    assert float(slide.get("stiffness")) == pytest.approx(1200.0)
    assert [g.get("name") for g in root.iter("geom")] == ["barrel", "collar", "nib"]
    tip = float(root.find(".//body[@name='nib']").get("pos").split()[2]) + common.NIB_SIZE[2] / 2
    assert tip == pytest.approx(common.NIB_TIP) and common.NIB_TIP == pytest.approx(0.063)


def test_an_unknown_marker_colour_is_refused_listing_the_markers():
    with pytest.raises(
        ValueError, match=r"unknown marker colour 'pink'; the markers are \['black', 'red', 'blue', 'green'\]"
    ):
        common.marker_file("pink")


def test_the_marker_options_name_the_asset_and_write_it_only_when_the_entity_is_built():
    # The options a task config holds name the marker (a saved config stays portable); the MJCF in its ink is
    # generated by resolve_runtime_file, which the entity calls when the env builds it.
    options = common.WhiteboardMarkerOptions(ink="blue")
    assert options.file == "whiteboard_marker.xml"
    path = options.resolve_runtime_file()
    assert os.path.isabs(path) and path.endswith("marker_blue.xml")
    r, g, b = common.COLORS["blue"]
    nib = ET.parse(path).getroot().find(".//geom[@name='nib']")
    assert [float(x) for x in nib.get("rgba").split()] == pytest.approx([r, g, b, 1.0])
    assert set(typing.get_args(common.MarkerColor)) == set(common.COLORS)
